# Diagram rendering — DM-005 and runtime edges reflected
# ---------------------------------------------------------------------------


class TestDiagramRendering:
    def test_render_diagram_includes_dm005_upward_edges(self):
        """The rendered diagram must mark DM-005 upward edges with UPWARD labels."""
        content = diagram.render_diagram()
        contexts = imports.load_contexts()
        for _obs in contexts.get("dm005_upward_edge_observations", []):
            # The DM-005 edges should appear as thick upward arrows
            assert "UPWARD" in content or "==>" in content

    def test_render_diagram_includes_runtime_edges(self):
        """The rendered diagram must include runtime (HTTP/spawn) edges."""
        content = diagram.render_diagram()
        contexts = imports.load_contexts()
        for re in contexts.get("runtime_edges", []):
            assert re["from"] in content
            assert re["to"] in content

    def test_render_diagram_has_layer_nodes(self):
        """The rendered diagram must include all layer nodes."""
        content = diagram.render_diagram()
        for node in ("app_server", "agent_server", "tools", "retrieval", "core"):
            assert node in content


