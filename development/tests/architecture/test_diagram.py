# Context registry divergence
# ---------------------------------------------------------------------------


class TestContextDivergence:
    def test_contexts_json_loads(self):
        contexts = imports.load_contexts()
        assert contexts["schema"] == "disclaude-architecture-contexts-v1"

    def test_contexts_have_package_layering(self):
        contexts = imports.load_contexts()
        layers = contexts["package_layering"]["layers"]
        assert len(layers) == 4
        # Top siblings
        assert "disco.app_server" in contexts["package_layering"]["top_siblings_independent"]
        assert "disco.agent_server" in contexts["package_layering"]["top_siblings_independent"]

    def test_contexts_have_dm005_observations(self):
        contexts = imports.load_contexts()
        observations = contexts.get("dm005_upward_edge_observations", [])
        assert len(observations) == 3
        for obs in observations:
            assert obs["observation_id"] == "DM-005"
            assert obs["tracked_in_importlinter"] is True

    def test_contexts_have_runtime_edges(self):
        contexts = imports.load_contexts()
        runtime_edges = contexts.get("runtime_edges", [])
        assert len(runtime_edges) >= 1
        # frontend -> agent_server HTTP edge
        assert any(
            e["from"] == "frontend" and e["to"] == "agent_server"
            for e in runtime_edges
        )

    def test_contexts_cross_feature_rejected(self):
        contexts = imports.load_contexts()
        frontend = contexts["bounded_contexts"]["frontend"]
        assert frontend["cross_feature_imports_rejected"] is True

    def test_permitted_edges_match_layering(self):
        """All permitted edges must point downward in the layering."""
        contexts = imports.load_contexts()
        layers = imports._build_layer_index(contexts)
        for edge in contexts["permitted_edges"]:
            from_pkg = edge["from"]
            to_pkg = edge["to"]
            from_layer = layers.get(from_pkg)
            to_layer = layers.get(to_pkg)
            if from_layer is not None and to_layer is not None:
                assert from_layer <= to_layer, (
                    f"permitted edge {from_pkg} -> {to_pkg} points upward"
                )

    def test_dm005_exemptions_match_contexts(self):
        """The DM-005 exemptions in imports must match the contexts registry."""
        contexts = imports.load_contexts()
        context_edges = {obs["edge"] for obs in contexts.get("dm005_upward_edge_observations", [])}
        assert set(imports._build_dm005_exemptions(contexts)) == context_edges
